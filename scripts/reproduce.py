"""Emit a portable, self-run receipt. Does not assert independence or authenticity."""
import hashlib
import json
from pathlib import Path
import platform
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SCENARIOS = ('ambiguity', 'approved-read', 'binding-mismatch', 'difference-only', 'explained')


def run(args):
    result = subprocess.run(args, cwd=ROOT, text=True, capture_output=True, timeout=120)
    return {'command': ['python3' if item == sys.executable else item for item in args],
            'exit_code': result.returncode, 'stdout': result.stdout, 'stderr': result.stderr}


def passed(commands):
    return bool(commands) and all(row['exit_code'] == 0 for row in commands)


def transcript():
    sections = ['# Captured synthetic terminal demonstration',
                'Generated by `python3 scripts/reproduce.py --demo`. These are local synthetic outputs, not a video, live platform read or independent reproduction.']
    for name in SCENARIOS:
        result = run([sys.executable, 'explore.py', 'scenario', name])
        if result['exit_code']:
            raise RuntimeError(f'Demo failed: {name}')
        sections.append('```text\n$ python3 explore.py scenario ' + name + '\n' + result['stdout'].rstrip() + '\n```')
    return '\n\n'.join(sections) + '\n'


def receipt():
    commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    dirty = bool(subprocess.check_output(['git', 'status', '--porcelain', '--untracked-files=all'], cwd=ROOT))
    names = subprocess.check_output(['git', 'ls-files', '-z'], cwd=ROOT).decode().split('\0')
    hashes = {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
              for name in names if name and (ROOT / name).is_file()}
    commands = [run([sys.executable, 'scripts/verify.py']), run([sys.executable, 'evaluate.py'])]
    return {'schema': 'local-reproduction-v1', 'evidence': 'synthetic_only',
            'independence': 'not_established', 'commit': commit,
            'working_tree_dirty': dirty, 'python': platform.python_version(),
            'tracked_file_sha256': hashes, 'commands': commands, 'passed': passed(commands)}


if __name__ == '__main__':
    if sys.argv[1:] == ['--demo']:
        print(transcript(), end='')
    elif not sys.argv[1:]:
        result = receipt()
        print(json.dumps(result, indent=2))
        raise SystemExit(0 if result['passed'] else 1)
    else:
        raise SystemExit('Usage: python3 scripts/reproduce.py [--demo]')
